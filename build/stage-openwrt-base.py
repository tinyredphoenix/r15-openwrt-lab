"""Package pinned standard OpenWrt base-files without foreign board overrides.

Produces an offline tar overlay, not a flashable image or a running bootstrap.
No host extraction, device nodes, services, mounts or firmware writes occur.
"""
import argparse,hashlib,io,json,posixpath,re,tarfile
from pathlib import Path,PurePosixPath
MANIFEST=Path(__file__).with_name('openwrt-base-manifest.json')
RUNTIME_PATH='/usr/sbin:/usr/bin:/sbin:/bin'
VERSION={
 '%D':'OpenWrt','%V':'21.02.7','%R':'r15-port-57a6d97',
 '%S':'r15/vendor-kernel','%A':'mips_4kec','%C':'R15 port experiment',
 '%t':'vendor-kernel','%d':'openwrt','%v':'21.02.7',
 '%u':'https://openwrt.org/','%b':'https://github.com/tinyredphoenix/r15-openwrt-lab/issues',
 '%s':'https://github.com/tinyredphoenix/r15-openwrt-lab',
 '%M':'D-Link','%m':'https://www.dlink.com/','%P':'R15','%h':'A1',
}
IDENTITY_FILES={'etc/banner','etc/openwrt_version','etc/openwrt_release','etc/device_info','usr/lib/os-release'}
def canonical(name):
 p=PurePosixPath(name)
 if p.is_absolute() or '..' in p.parts or not p.parts:raise ValueError('Unsafe source member')
 return p.as_posix()
def assemble(source,output,report_path):
 manifest=json.loads(MANIFEST.read_text());prepared=[];seen=set()
 for record in manifest['files']:
  name=canonical(record['path'])
  if name in seen:raise ValueError('Duplicate base-files entry')
  seen.add(name);incoming=source/name
  if not incoming.parent.resolve().is_relative_to(source.resolve()):raise ValueError('Escaping source parent')
  if record['mode']=='120000' and incoming.is_symlink():
   data=incoming.readlink().as_posix().encode()
  else:
   if incoming.is_symlink() or not incoming.resolve().is_relative_to(source.resolve()):raise ValueError('Linked/escaping source')
   data=incoming.read_bytes()
  if hashlib.sha256(data).hexdigest()!=record['sha256']:raise ValueError('Pinned base-files source mismatch')
  git_hash=hashlib.sha1(('blob '+str(len(data))+'\0').encode()+data).hexdigest()
  if git_hash!=record['git_blob']:raise ValueError('Pinned Git blob mismatch')
  member=tarfile.TarInfo(name);member.uid=member.gid=member.mtime=0
  if record['mode']=='120000':
   link=data.decode();resolved=posixpath.normpath(posixpath.join(posixpath.dirname(name),link))
   if link.startswith('/') or resolved=='..' or resolved.startswith('../'):raise ValueError('Escaping base-files symlink')
   member.type=tarfile.SYMTYPE;member.mode=0o777;member.linkname=link;payload=None
  else:
   if record['mode'] not in ('100644','100755'):raise ValueError('Unexpected Git mode')
   data=data.replace(b'%PATH%',RUNTIME_PATH.encode())
   if name in IDENTITY_FILES:
    for token,value in VERSION.items():data=data.replace(token.encode(),value.encode())
    if re.search(rb'%[A-Za-z]',data):raise ValueError('Unresolved version template')
   if b'%PATH%' in data:raise ValueError('Unresolved runtime path')
   member.mode=int(record['mode'][-3:],8);member.size=len(data);payload=data
  prepared.append((member,payload))
 # Generated by base-files' ImageConfigOptions, not a separate init framework.
 config=('pi_suppress_stderr=""\nfs_failsafe_wait_timeout=2\n'
         'pi_init_path="'+RUNTIME_PATH+'"\npi_init_env=""\npi_init_cmd="/sbin/init"\n'
         'pi_init_suppress_stderr=""\npi_ifname=""\npi_ip="192.168.77.1"\n'
         'pi_netmask="255.255.255.0"\npi_broadcast="192.168.77.255"\n'
         'pi_preinit_net_messages=""\npi_preinit_no_failsafe_netmsg=""\npi_preinit_no_failsafe=""\n').encode()
 m=tarfile.TarInfo('lib/preinit/00_preinit.conf');m.mode=0o644;m.size=len(config);prepared.append((m,config))
 # Rootfs needs a console before procd can perform its own /dev setup.
 m=tarfile.TarInfo('dev/console');m.type=tarfile.CHRTYPE;m.mode=0o600;m.devmajor=5;m.devminor=1;prepared.append((m,None))
 if output.exists() or report_path.exists():raise ValueError('Refusing to overwrite foundation output')
 with output.open('xb') as stream,tarfile.open(fileobj=stream,mode='w',format=tarfile.PAX_FORMAT) as archive:
  for member,payload in prepared:archive.addfile(member,io.BytesIO(payload) if payload is not None else None)
 result={'scope':'Standard OpenWrt generic base-files foundation; offline assembly only',
         'source_commit':manifest['commit'],'upstream_files':len(manifest['files']),
         'generated_files':['lib/preinit/00_preinit.conf','dev/console'],
         'sdk_board_files_imported':False,'custom_pid1_wrapper':False,'hardware_executed':False,
         'boot_framework_complete':False,'flashable':False,
         'remaining':['R15 board preinit/switch/calibration adapter','Matching overlay module and standard fstools mount',
                      'Package service enablement and management provisioning','R15-specific sysupgrade validation and recovery',
                      'Native PID1/boot qualification'],
         'tar_sha256':hashlib.sha256(output.read_bytes()).hexdigest()}
 report_path.write_text(json.dumps(result,indent=2)+'\n');return result
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__)
 for name in ('source','output','report'):p.add_argument('--'+name,type=Path,required=True)
 a=p.parse_args();print(json.dumps(assemble(a.source,a.output,a.report),indent=2))
